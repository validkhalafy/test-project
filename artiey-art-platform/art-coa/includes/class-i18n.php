final class I18n
{
    private static string $lang = 'fa';

    public static function init(): void
    {
        $opt = get_option('wp_art_coa_settings', []);
        $lang = $opt['language'] ?? 'fa';
        self::$lang = in_array($lang, ['fa', 'en'], true) ? $lang : 'fa';

        // Allow ?art_coa_lang=en override for preview
        if (isset($_GET['art_coa_lang']) && in_array($_GET['art_coa_lang'], ['fa', 'en'], true)) {
            self::$lang = sanitize_key((string) $_GET['art_coa_lang']);
        }

        load_plugin_textdomain('wp-art-coa-pro', false, dirname(WP_ART_COA_BASENAME) . '/languages');
    }

    public static function lang(): string
    {
        return self::$lang;
    }

    public static function is_fa(): bool
    {
        return self::$lang === 'fa';
    }

    public static function t(string $key, array $replace = []): string
    {
        $strings = self::strings();
        $text = $strings[self::$lang][$key] ?? $strings['en'][$key] ?? $key;
        foreach ($replace as $k => $v) {
            $text = str_replace('{' . $k . '}', (string) $v, $text);
        }
        return $text;
    }

    public static function e(string $key, array $replace = []): void
    {
        echo esc_html(self::t($key, $replace));
    }

