    private static function get_public_stats_data() {
        $cached = get_transient('wp_coa_pro_public_stats_cache');
        if (is_array($cached) && isset($cached['total'], $cached['active'], $cached['galleries'])) {
            return $cached;
        }
        global $wpdb;
        $certificate_table = $wpdb->prefix . 'coa_certificates';
        $total = (int) $wpdb->get_var("SELECT COUNT(*) FROM {$certificate_table}");
        $active = (int) $wpdb->get_var($wpdb->prepare("SELECT COUNT(*) FROM {$certificate_table} WHERE status = %s", 'active'));
        $data = array(
            'total' => $total,
            'active' => $active,
            'galleries' => (int) $wpdb->get_var("SELECT COUNT(*) FROM " . WP_COA_Pro_Galleries::table_name() . " WHERE status = 'active'"),
        );
        set_transient('wp_coa_pro_public_stats_cache', $data, 5 * MINUTE_IN_SECONDS);
        return $data;
    }

