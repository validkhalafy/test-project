    private static function find_managed_page($key) {
        $pages = get_posts(array(
            'post_type' => 'page',
            'post_status' => array('publish', 'draft', 'private', 'pending'),
            'posts_per_page' => 1,
            'fields' => 'all',
            'meta_key' => '_wp_coa_pro_managed_page',
            'meta_value' => sanitize_key($key),
            'orderby' => 'ID',
            'order' => 'ASC',
        ));
        return !empty($pages) ? $pages[0] : null;
    }


    /**
     * Resolve a plugin-managed page safely. An option ID alone is not proof of ownership:
     * WordPress may recycle IDs after deletion, and stale/corrupt options must never turn
     * an unrelated page into the verification or profile destination.
     */
    private static function get_managed_page($key) {
        $key = sanitize_key((string) $key);
        static $managed_keys = null;
        if ($managed_keys === null) {
            $managed_keys = array_fill_keys(array_keys(self::recommended_pages()), true);
        }
        if ($key === '' || !isset($managed_keys[$key])) {
            return null;
        }

        $ids = get_option(self::PAGE_IDS_OPTION, array());
        if (!is_array($ids)) {
            $ids = array();
        }

        $page = !empty($ids[$key]) ? get_post(absint($ids[$key])) : null;
        $is_managed = $page
            && isset($page->ID, $page->post_type, $page->post_status)
            && $page->post_type === 'page'
            && in_array($page->post_status, array('publish', 'draft', 'private', 'pending'), true)
            && get_post_meta((int) $page->ID, '_wp_coa_pro_managed_page', true) === $key;

        if (!$is_managed) {
            $page = self::find_managed_page($key);
            $is_managed = $page
                && isset($page->ID, $page->post_type, $page->post_status)
                && $page->post_type === 'page'
                && in_array($page->post_status, array('publish', 'draft', 'private', 'pending'), true)
                && get_post_meta((int) $page->ID, '_wp_coa_pro_managed_page', true) === $key;
        }

        if (!$is_managed) {
            if (isset($ids[$key])) {
                unset($ids[$key]);
                update_option(self::PAGE_IDS_OPTION, $ids, false);
            }
            return null;
        }

        if ((int) ($ids[$key] ?? 0) !== (int) $page->ID) {
            $ids[$key] = (int) $page->ID;
            update_option(self::PAGE_IDS_OPTION, $ids, false);
        }
        return $page;
    }

