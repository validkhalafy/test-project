    public static function get_managed_page_url($key) {
        if ($key === 'artist_directory' && class_exists('\\WPArtCOA\\ContentSync')) {
            return \WPArtCOA\ContentSync::artist_archive_url();
        }
        $page = self::get_managed_page($key);
        if (!$page || $page->post_status !== 'publish') {
            return '';
        }
        $url = get_permalink((int) $page->ID);
        return $url ? $url : '';
    }

    private static function resolve_language($language) {
        $language = sanitize_key((string) $language);
        if ($language === 'site') {
            $locale = function_exists('determine_locale') ? determine_locale() : get_locale();
            return strpos(strtolower($locale), 'fa') === 0 ? 'fa' : 'en';
        }
        return in_array($language, array('fa', 'en', 'both'), true) ? $language : 'fa';
    }

    private static function localized_profile($primary, $english, $language) {
        $primary = is_scalar($primary) ? (string) $primary : '';
        $english = is_scalar($english) ? (string) $english : '';
        if ($language === 'en') { return $english !== '' ? $english : $primary; }
        if ($language === 'both' && $english !== '') { return $primary . ' / ' . $english; }
        return $primary !== '' ? $primary : $english;
    }

    private static function activity_name($activity, $language) {
        if ($language === 'fa') { return WP_COA_Pro_Galleries::activity_label($activity, 'fa'); }
        if ($language === 'en') { return WP_COA_Pro_Galleries::activity_label($activity, 'en'); }
        return WP_COA_Pro_Galleries::activity_label($activity, 'both');
    }

    private static function template_name($template, $language) {
        $templates = WP_COA_Pro_Galleries::templates();
        if (!isset($templates[$template])) { return (string) $template; }
        if ($language === 'fa') { return $templates[$template][0]; }
        if ($language === 'en') { return $templates[$template][1]; }
        return $templates[$template][0] . ' / ' . $templates[$template][1];
    }

    private static function default_primary() {
        $settings = class_exists('WP_COA_Pro_Admin') ? WP_COA_Pro_Admin::get_settings() : array();
        return isset($settings['primary_color']) && sanitize_hex_color($settings['primary_color']) ? $settings['primary_color'] : '#65513b';
    }

    private static function default_accent() {
        $settings = class_exists('WP_COA_Pro_Admin') ? WP_COA_Pro_Admin::get_settings() : array();
        return isset($settings['accent_color']) && sanitize_hex_color($settings['accent_color']) ? $settings['accent_color'] : '#b29a68';
    }
