    public static function handle_create_pages() {
        if (!current_user_can('manage_coa_certificates')) {
            wp_die(esc_html__('You do not have permission to create COA pages.', 'wp-coa-pro'));
        }
        check_admin_referer('wp_coa_create_recommended_pages');

        $ids = get_option(self::PAGE_IDS_OPTION, array());
        if (!is_array($ids)) {
            $ids = array();
        }
        $created = 0;
        $existing = 0;
        $errors = 0;
        foreach (self::recommended_pages() as $key => $spec) {
            $page = self::get_managed_page($key);
            if ($page) {
                $ids[$key] = (int) $page->ID;
                $existing++;
                continue;
            }
            $page_id = wp_insert_post(array(
                'post_type' => 'page',
                'post_status' => 'publish',
                'post_title' => $spec['title'],
                'post_name' => $spec['slug'],
                'post_content' => str_replace('\\n', "\n", $spec['content']),
                'comment_status' => 'closed',
                'ping_status' => 'closed',
                'meta_input' => array('_wp_coa_pro_managed_page' => $key),
            ), true);
            if (is_wp_error($page_id) || !$page_id) {
                unset($ids[$key]);
                $errors++;
                continue;
            }
            $ids[$key] = (int) $page_id;
            $created++;
        }
        update_option(self::PAGE_IDS_OPTION, $ids, false);
        if (class_exists('WP_COA_Pro_SEO')) {
            WP_COA_Pro_SEO::register_rewrite_rules();
            flush_rewrite_rules(false);
        }
        $url = add_query_arg(array(
            'page' => 'wp-coa-pro-pages',
            'created' => $created,
            'existing' => $existing,
            'page_errors' => $errors,
        ), admin_url('admin.php'));
        wp_safe_redirect($url);
        exit;
    }

