    /**
     * Identify a page that is already serving the artist archive. We adopt it only
     * when its saved content or Elementor document explicitly contains an artist
     * directory in their content or Elementor document. A new migration may append it
     * to an existing /artists/ page while preserving that page's current design.
     */
    private static function is_artist_archive_page($page) {
        if (!$page || !isset($page->ID, $page->post_type, $page->post_name, $page->post_parent)
            || $page->post_type !== 'page' || $page->post_name !== 'artists' || (int) $page->post_parent !== 0
            || !in_array((string) ($page->post_status ?? ''), array('publish', 'draft', 'private', 'pending'), true)) {
            return false;
        }

        $content = (string) ($page->post_content ?? '');
        if (preg_match('/\[(?:coa_artist_directory|artiey_artist_archive)\b/i', $content)) {
            return true;
        }
        if (preg_match_all('/\[coa_profile_directory\b([^\]]*)\]/i', $content, $matches, PREG_SET_ORDER)) {
            foreach ($matches as $match) {
                $attrs = (string) ($match[1] ?? '');
                if (!preg_match('/\btype\s*=\s*(["\']?)collector\1/i', $attrs)) {
                    return true;
                }
            }
        }

        $document = get_post_meta((int) $page->ID, '_elementor_data', true);
        if (!is_string($document) || $document === '') {
            return false;
        }
        $decoded = json_decode($document, true);
        if (!is_array($decoded)) {
            // Older Elementor documents may be valid JSON fragments but not decodable arrays.
            return (bool) preg_match('/"widgetType"\s*:\s*"wp-coa-person-directory"/', $document)
                && !preg_match('/"profile_type"\s*:\s*"collector"/', $document);
        }
        $has_artist_widget = false;
        $walk = static function ($node) use (&$walk, &$has_artist_widget) {
            if (!is_array($node) || $has_artist_widget) { return; }
            $settings = isset($node['settings']) && is_array($node['settings']) ? $node['settings'] : array();
            if (($node['widgetType'] ?? '') === 'wp-coa-person-directory') {
                $type = isset($settings['profile_type']) ? (string) $settings['profile_type'] : 'artist';
                if ($type === 'artist') { $has_artist_widget = true; return; }
            }
            if (($node['widgetType'] ?? '') === 'shortcode'
                && preg_match('/\[(?:artiey_artist_archive|coa_artist_directory)\b/i', (string) ($settings['shortcode'] ?? ''))) {
                $has_artist_widget = true;
                return;
            }
            foreach ($node as $child) {
                if (is_array($child)) { $walk($child); }
            }
        };
        $walk($decoded);
        return $has_artist_widget;
    }

    /**
     * Keep /artists/ as the one artist archive. Adopt an existing page at that path,
     * preserve its Gutenberg/Elementor design, and add the canonical directory only
     * when it is not already present. A previous managed archive page becomes a 301 alias.
     */
    public static function maybe_unify_artist_archive_page() {
        $migration_key = 'wp_coa_pro_artist_archive_unified_23212';
        $canonical_page = function_exists('get_page_by_path') ? get_page_by_path('artists', OBJECT, 'page') : null;
        $canonical_candidate = $canonical_page && isset($canonical_page->ID, $canonical_page->post_type, $canonical_page->post_status, $canonical_page->post_name, $canonical_page->post_parent)
            && $canonical_page->post_type === 'page'
            && $canonical_page->post_name === 'artists'
            && (int) $canonical_page->post_parent === 0
            && in_array((string) $canonical_page->post_status, array('publish', 'draft', 'private', 'pending'), true);

        // Repair a canonical archive accidentally left in a non-public status. Only
        // promote it when Artiey owns the page or the page itself contains an explicit
        // artist-directory shortcode/Elementor widget; never publish an unrelated draft.
        if ($canonical_candidate && (string) $canonical_page->post_status !== 'publish') {
            $is_managed_archive = get_post_meta((int) $canonical_page->ID, '_wp_coa_pro_managed_page', true) === 'artist_directory';
            if ($is_managed_archive || self::is_artist_archive_page($canonical_page)) {
                if (function_exists('wp_update_post')) {
                    wp_update_post(array('ID' => (int) $canonical_page->ID, 'post_status' => 'publish'));
                    if (function_exists('clean_post_cache')) { clean_post_cache((int) $canonical_page->ID); }
                    $canonical_page = get_post((int) $canonical_page->ID);
                }
            }
        }
        $canonical_is_page = $canonical_candidate && $canonical_page
            && (string) ($canonical_page->post_status ?? '') === 'publish';

        // A one-time migration marker must not keep a deleted/moved archive broken
        // forever. If the canonical page still exists, leave its current design alone.
        if (get_option($migration_key)) {
            if ($canonical_is_page) {
                return;
            }
            delete_option($migration_key);
        }

        $managed_page = self::get_managed_page('artist_directory');

        // An existing /artists/ page owns the requested canonical path. Preserve its
        // current design/content and add the directory only during initial adoption.
        if ($canonical_is_page) {
            if ($managed_page && (int) $managed_page->ID !== (int) $canonical_page->ID) {
                update_post_meta((int) $managed_page->ID, '_wp_coa_pro_artist_archive_legacy_redirect', 1);
                delete_post_meta((int) $managed_page->ID, '_wp_coa_pro_managed_page');
            }
            self::ensure_artist_archive_output($canonical_page);
            update_post_meta((int) $canonical_page->ID, '_wp_coa_pro_managed_page', 'artist_directory');
            $ids = get_option(self::PAGE_IDS_OPTION, array());
            $ids = is_array($ids) ? $ids : array();
            $ids['artist_directory'] = (int) $canonical_page->ID;
            update_option(self::PAGE_IDS_OPTION, $ids, false);
            update_option($migration_key, 1, false);
            return;
        }

        // If the old managed page was deleted, recreate the public archive only when
        // the root slug is genuinely free. Never steal /artists/ from another object.
        if (!$managed_page && function_exists('wp_insert_post')) {
            $path_conflict = function_exists('get_page_by_path') ? get_page_by_path('artists', OBJECT, 'any') : null;
            if (!$path_conflict) {
                $spec = self::recommended_pages()['artist_directory'];
                $created_id = wp_insert_post(array(
                    'post_type' => 'page',
                    'post_status' => 'publish',
                    'post_title' => $spec['title'],
                    'post_name' => 'artists',
                    'post_content' => str_replace('\\n', "\n", $spec['content']),
                    'comment_status' => 'closed',
                    'ping_status' => 'closed',
                    'meta_input' => array('_wp_coa_pro_managed_page' => 'artist_directory'),
                ), true);
                if (!is_wp_error($created_id) && absint($created_id) > 0) {
                    $managed_page = get_post(absint($created_id));
                    $ids = get_option(self::PAGE_IDS_OPTION, array());
                    $ids = is_array($ids) ? $ids : array();
                    $ids['artist_directory'] = absint($created_id);
                    update_option(self::PAGE_IDS_OPTION, $ids, false);
                    update_option('artiey_aet_flush', 1, false);
                }
            }
        }

        if (!$managed_page || !isset($managed_page->ID, $managed_page->post_type) || $managed_page->post_type !== 'page') {
            // Leave the migration retryable; the URL cache/rewrite repair can still complete.
            return;
        }

        self::ensure_artist_archive_output($managed_page);
        $update = array('ID' => (int) $managed_page->ID);
        if ((string) ($managed_page->post_name ?? '') !== 'artists') {
            $update['post_name'] = 'artists';
        }
        if ((int) ($managed_page->post_parent ?? 0) !== 0) {
            $update['post_parent'] = 0;
        }
        // A managed canonical directory must be public; a stale draft/private status
        // otherwise makes /artists/ resolve to a 404 for anonymous visitors.
        if ((string) ($managed_page->post_status ?? '') !== 'publish') {
            $update['post_status'] = 'publish';
        }
        if (count($update) > 1 && function_exists('wp_update_post')) {
            wp_update_post($update);
            update_option('artiey_aet_flush', 1, false);
        }
        update_post_meta((int) $managed_page->ID, '_wp_coa_pro_managed_page', 'artist_directory');
        $ids = get_option(self::PAGE_IDS_OPTION, array());
        $ids = is_array($ids) ? $ids : array();
        $ids['artist_directory'] = (int) $managed_page->ID;
        update_option(self::PAGE_IDS_OPTION, $ids, false);
        update_option($migration_key, 1, false);
    }

    /** Make sure the canonical page actually renders the archive while leaving existing design intact. */
    private static function ensure_artist_archive_output($page) {
        if (!$page || !isset($page->ID)) { return; }
        $page_id = (int) $page->ID;
        $content = (string) ($page->post_content ?? '');
        $shortcode = '[artiey_artist_archive columns="3" per_page="12" ajax="yes"]';

        // Upgrade old shortcode aliases without touching collector directories or custom copy.
        $updated_content = preg_replace('/\[coa_artist_directory\b[^\]]*\]/i', $shortcode, $content);
        $updated_content = preg_replace_callback('/\[coa_profile_directory\b([^\]]*)\]/i', static function ($match) use ($shortcode) {
            $attrs = (string) ($match[1] ?? '');
            return preg_match('/\btype\s*=\s*(["\']?)collector\1/i', $attrs) ? $match[0] : $shortcode;
        }, (string) $updated_content);
        if (preg_match('/\[(?:artiey_artist_archive|coa_artist_directory)\b/i', (string) $updated_content)
            || preg_match('/\[coa_profile_directory\b(?![^\]]*\btype\s*=\s*(["\']?)collector\1)[^\]]*\]/i', (string) $updated_content)) {
            if ((string) $updated_content !== $content && function_exists('wp_update_post')) {
                wp_update_post(array('ID' => $page_id, 'post_content' => $updated_content));
            }
            return;
        }

        // If the page uses Elementor, append a native Shortcode widget to its existing
        // document instead of changing post_content (which Elementor may not render).
        $elementor_document = get_post_meta($page_id, '_elementor_data', true);
        if (is_string($elementor_document) && $elementor_document !== '') {
            $decoded = json_decode($elementor_document, true);
            if (is_array($decoded)) {
                $has_artist_output = false;
                $walk = static function ($node) use (&$walk, &$has_artist_output) {
                    if (!is_array($node) || $has_artist_output) { return; }
                    $widget_type = (string) ($node['widgetType'] ?? '');
                    $settings = isset($node['settings']) && is_array($node['settings']) ? $node['settings'] : array();
                    if ($widget_type === 'wp-coa-person-directory'
                        && (string) ($settings['profile_type'] ?? 'artist') === 'artist') {
                        $has_artist_output = true;
                        return;
                    }
                    if ($widget_type === 'shortcode' && preg_match('/\[(?:artiey_artist_archive|coa_artist_directory)\b/i', (string) ($settings['shortcode'] ?? ''))) {
                        $has_artist_output = true;
                        return;
                    }
                    foreach ($node as $child) { if (is_array($child)) { $walk($child); } }
                };
                $walk($decoded);
                if ($has_artist_output) { return; }

                $seed = substr(md5('artiey-artist-archive-' . $page_id), 0, 8);
                $section_id = $seed;
                $column_id = substr(md5($seed . '-column'), 0, 8);
                $widget_id = substr(md5($seed . '-widget'), 0, 8);
                $decoded[] = array(
                    'id' => $section_id,
                    'elType' => 'section',
                    'settings' => array('layout' => 'full_width', 'content_width' => 'full'),
                    'elements' => array(array(
                        'id' => $column_id,
                        'elType' => 'column',
                        'settings' => array('_column_size' => 100),
                        'elements' => array(array(
                            'id' => $widget_id,
                            'elType' => 'widget',
                            'settings' => array('shortcode' => $shortcode),
                            'elements' => array(),
                            'widgetType' => 'shortcode',
                        )),
                        'isInner' => false,
                    )),
                    'isInner' => false,
                );
                update_post_meta($page_id, '_elementor_data', wp_slash(wp_json_encode($decoded)));
                if (function_exists('update_post_meta')) {
                    update_post_meta($page_id, '_elementor_css', '');
                }
                return;
            }
        }

        // Gutenberg/classic pages retain their existing blocks and receive the archive below.
        if (function_exists('wp_update_post')) {
            $append = ($content !== '' ? "\n\n" : '') . '<!-- wp:shortcode -->' . $shortcode . '<!-- /wp:shortcode -->';
            wp_update_post(array('ID' => $page_id, 'post_content' => $content . $append));
        }
    }

    /** Redirect the superseded managed archive page after the /artists/ page is adopted. */
    public static function redirect_legacy_artist_archive_page() {
        if (!function_exists('is_page') || !is_page() || !function_exists('get_queried_object_id')) { return; }
        $page_id = absint(get_queried_object_id());
        if (!$page_id || get_post_meta($page_id, '_wp_coa_pro_artist_archive_legacy_redirect', true) !== '1'
            && get_post_meta($page_id, '_wp_coa_pro_artist_archive_legacy_redirect', true) !== 1) {
            return;
        }
        $target = class_exists('\\WPArtCOA\\ContentSync') ? \WPArtCOA\ContentSync::artist_archive_url() : home_url('/artists/');
        $target_path = wp_parse_url($target, PHP_URL_PATH);
        $request_path = isset($_SERVER['REQUEST_URI']) ? wp_parse_url(wp_unslash($_SERVER['REQUEST_URI']), PHP_URL_PATH) : '';
        if (!is_string($target_path) || !is_string($request_path)
            || untrailingslashit($target_path) === untrailingslashit($request_path)) { return; }
        wp_safe_redirect($target, 301, 'Artiey Art Platform');
        exit;
    }

    public static function register_style_handle() {
        if (!wp_style_is('wp-coa-pro-components', 'registered')) {
            wp_register_style(
                'wp-coa-pro-components',
                WP_COA_PRO_URL . 'assets/css/public-components.css',
                array(),
                WP_COA_PRO_VERSION
            );
        }
    }

    private static $theme_variables_added = false;

    public static function register_assets() {
        self::register_style_handle();
        // Skip settings reads and inline style generation on pages that do not use COA components.
        if (is_admin() || !self::should_enqueue_public_assets()) { return; }
        self::enqueue_public_assets();
    }

    private static function add_theme_variables() {
        if (self::$theme_variables_added || !wp_style_is('wp-coa-pro-components', 'registered')) { return; }
        $settings = class_exists('WP_COA_Pro_Admin') ? WP_COA_Pro_Admin::get_settings() : array();
        $primary = isset($settings['primary_color']) && sanitize_hex_color($settings['primary_color']) ? $settings['primary_color'] : '#65513b';
        $accent = isset($settings['accent_color']) && sanitize_hex_color($settings['accent_color']) ? $settings['accent_color'] : '#b29a68';
        wp_add_inline_style('wp-coa-pro-components', '.wp-coa-directory,.wp-coa-public-stats,.wp-coa-certificate-guide{--wp-coa-directory-primary:' . $primary . ';--wp-coa-directory-accent:' . $accent . ';--wp-coa-stats-primary:' . $primary . ';--wp-coa-stats-accent:' . $accent . ';--wp-coa-guide-primary:' . $primary . ';--wp-coa-guide-accent:' . $accent . ';}');
        self::$theme_variables_added = true;
    }

    private static function enqueue_assets() { self::enqueue_public_assets(); }

    /** Public bridge used by profile shortcodes and Elementor render callbacks. */
    public static function enqueue_public_assets() {
        self::register_style_handle();
        wp_enqueue_style('wp-coa-pro-components');
        self::add_theme_variables();
    }

    /** Avoid downloading the shared component stylesheet on unrelated pages. */
    private static function should_enqueue_public_assets() {
        if (!is_singular()) {
            return false;
        }
        $post_id = absint(get_queried_object_id());
        if (!$post_id) {
            return false;
        }
        $post = get_post($post_id);
        if (!$post) {
            return false;
        }
        $content = (string) $post->post_content;
        // A single scan is cheaper than invoking has_shortcode() repeatedly on long Elementor pages.
        if ($content !== '' && preg_match('/\[(?:coa_verify|coa_gallery_directory|coa_public_stats|coa_gallery_profile|coa_certificate_guide|coa_artist_directory|coa_collector_directory|coa_profile_directory|coa_profile_view|artiey_artist_archive)(?=[\s\]])/', $content)) {
            return true;
        }
        // Elementor's saved widget JSON can be large. Scan it only if Elementor is active.
        if (!did_action('elementor/loaded') && !class_exists('\Elementor\Plugin')) { return false; }
        $elementor_data = get_post_meta($post_id, '_elementor_data', true);
        if (is_string($elementor_data) && $elementor_data !== '') {
            foreach (array(
                'wp-coa-certificate-verification', 'wp-coa-gallery-directory', 'wp-coa-public-statistics',
                'wp-coa-gallery-profile', 'wp-coa-certificate-guide', 'wp-coa-person-directory',
                'wp-coa-person-profile', 'coa_verify', 'coa_profile_view', 'coa_artist_directory', 'coa_collector_directory'
            ) as $needle) {
                if (strpos($elementor_data, $needle) !== false) {
                    return true;
                }
            }
        }
        return false;
    }

